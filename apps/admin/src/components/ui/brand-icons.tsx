import type { ReactNode, SVGProps } from "react";

/**
 * Brand icons. lucide-react 1.0 dropped its brand glyphs, so these keep the
 * exact drawings lucide shipped before (ISC licence) behind the same props
 * (`size`, `strokeWidth`, `className`, …) used across the app.
 */
type BrandIconProps = Omit<SVGProps<SVGSVGElement>, "ref"> & {
  size?: number | string;
};

const createBrandIcon = (name: string, children: ReactNode) => {
  const Icon = ({ size = 24, strokeWidth = 2, ...props }: BrandIconProps) => (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {children}
    </svg>
  );
  Icon.displayName = name;
  return Icon;
};

